//! Native testing adapter: compile WASM with Cranelift Speed before execution.
//! Guest RAM and devices stay in the exclusively owned Rust host.
#![cfg(not(target_arch = "wasm32"))]
use doslet_x86_wasm::host::{Host, Runtime};
use std::time::Instant;
use wasmtime::{
    Caller, Config, Engine, Global, GlobalType, Inlining, Linker, Memory, MemoryType, Module,
    Mutability, OptLevel, RegallocAlgorithm, Store, Strategy, TypedFunc, Val, ValType,
};

pub mod probe;
pub mod procedure;
pub mod procedure_memory;
pub mod shared_runtime;
pub mod static_program;

/// Host storage for native code compiled by this adapter. The library never
/// opens files. `engine` fingerprints the Wasmtime version, configuration and
/// target; `load` must return only bytes the host earlier received from `store`
/// for the same WASM source and fingerprint, because they execute as native code.
pub trait CompiledCache {
    fn load(&mut self, wasm: &[u8], engine: u64) -> Option<Vec<u8>>;
    fn store(&mut self, wasm: &[u8], engine: u64, compiled: &[u8]);
}

/// Owns code generated by this process or returned by a host `CompiledCache`.
pub struct Artifact {
    engine: Engine,
    module: Module,
    serialized: Vec<u8>,
    source: Vec<u8>,
    pub compile_seconds: f64,
    pub load_seconds: f64,
}
impl Artifact {
    pub fn compile(wasm: &[u8]) -> Result<Self, String> {
        Self::compile_on(&Self::engine()?, wasm)
    }
    /// Reuse a cached compilation. An entry Wasmtime rejects, for example from
    /// another version or CPU, is recompiled and replaced.
    pub fn compile_cached(wasm: &[u8], cache: &mut dyn CompiledCache) -> Result<Self, String> {
        let engine = Self::engine()?;
        let fingerprint = {
            use std::hash::{Hash, Hasher};
            let mut hasher = std::hash::DefaultHasher::new();
            engine.precompile_compatibility_hash().hash(&mut hasher);
            hasher.finish()
        };
        if let Some(serialized) = cache.load(wasm, fingerprint) {
            let start = Instant::now();
            if let Ok(module) = load_cached_artifact(&engine, &serialized) {
                return Ok(Self {
                    engine,
                    module,
                    serialized,
                    source: wasm.to_vec(),
                    compile_seconds: 0.0,
                    load_seconds: start.elapsed().as_secs_f64(),
                });
            }
        }
        let artifact = Self::compile_on(&engine, wasm)?;
        cache.store(wasm, fingerprint, &artifact.serialized);
        Ok(artifact)
    }
    fn engine() -> Result<Engine, String> {
        let mut config = Config::new();
        config
            .strategy(Strategy::Cranelift)
            .cranelift_opt_level(OptLevel::Speed)
            .cranelift_regalloc_algorithm(RegallocAlgorithm::Backtracking)
            .compiler_inlining(Inlining::Yes);
        Engine::new(&config).map_err(|e| e.to_string())
    }
    fn compile_on(engine: &Engine, wasm: &[u8]) -> Result<Self, String> {
        let start = Instant::now();
        let serialized = engine
            .precompile_module(wasm)
            .map_err(|e| format!("{e:#}"))?;
        let compile_seconds = start.elapsed().as_secs_f64();
        let start = Instant::now();
        let module = load_own_artifact(engine, &serialized)?;
        let load_seconds = start.elapsed().as_secs_f64();
        Ok(Self {
            engine: engine.clone(),
            module,
            serialized,
            source: wasm.to_vec(),
            compile_seconds,
            load_seconds,
        })
    }
    /// Host tools may persist these local machine-specific bytes for inspection.
    /// Loading arbitrary file bytes is intentionally not exposed by this adapter.
    pub fn serialized(&self) -> &[u8] {
        &self.serialized
    }
    pub fn instantiate<R: Runtime + 'static>(&self, host: Host<R>) -> Result<Runner<R>, String> {
        if host.translation().wasm() != self.source {
            return Err("AOT artifact and host profile differ".into());
        }
        let mut store = Store::new(
            &self.engine,
            State {
                host,
                memory: None,
                error: None,
            },
        );
        // The native host owns this scratch memory; the module imports it at base 0.
        let pages = doslet_x86_wasm::STATE_BYTES.div_ceil(65536) as u32;
        let memory = Memory::new(&mut store, MemoryType::new(pages, Some(pages)))
            .map_err(|e| e.to_string())?;
        store.data_mut().memory = Some(memory);
        let base = Global::new(
            &mut store,
            GlobalType::new(ValType::I32, Mutability::Const),
            Val::I32(0),
        )
        .map_err(|e| e.to_string())?;
        let mut linker = Linker::new(&self.engine);
        linker
            .define(&store, "doslet", "memory", memory)
            .and_then(|linker| linker.define(&store, "doslet", "base", base))
            .map_err(|e| e.to_string())?;
        linker
            .func_wrap(
                "doslet",
                "poll",
                |mut caller: Caller<'_, State<R>>, completed: u32, remaining: u32| -> i32 {
                    let memory = caller.data().memory.expect("scratch memory");
                    let (bytes, state) = memory.data_and_store_mut(&mut caller);
                    match state.host.poll(completed, remaining, bytes) {
                        Ok(id) => id,
                        Err(error) => {
                            state.error = Some(error);
                            -2
                        }
                    }
                },
            )
            .map_err(|e| e.to_string())?;
        let instance = linker
            .instantiate(&mut store, &self.module)
            .map_err(|e| e.to_string())?;
        let run = instance
            .get_typed_func::<u32, u32>(&mut store, "run")
            .map_err(|e| e.to_string())?;
        Ok(Runner {
            store,
            run,
            _memory: memory,
            failed: false,
        })
    }
}

// The only unsafe operation is loading native bytes just compiled by this exact
// Engine. Callers cannot construct Artifact from serialized data or replace it.
#[allow(unsafe_code)]
fn load_own_artifact(engine: &Engine, serialized: &[u8]) -> Result<Module, String> {
    // SAFETY: this private function is called only with Engine::precompile_module
    // output from the same engine, retained unchanged and never read from disk.
    unsafe { Module::deserialize(engine, serialized) }.map_err(|e| e.to_string())
}

#[allow(unsafe_code)]
fn load_cached_artifact(engine: &Engine, serialized: &[u8]) -> Result<Module, String> {
    // SAFETY: `CompiledCache` requires bytes this adapter produced with
    // Engine::precompile_module. Wasmtime rejects output of an incompatible
    // version, configuration or target before mapping it as code.
    unsafe { Module::deserialize(engine, serialized) }.map_err(|e| e.to_string())
}

struct State<R: Runtime> {
    host: Host<R>,
    memory: Option<Memory>,
    error: Option<doslet_x86_wasm::host::Error<R::Error>>,
}
pub struct Runner<R: Runtime + 'static> {
    store: Store<State<R>>,
    run: TypedFunc<u32, u32>,
    _memory: Memory,
    failed: bool,
}
impl<R: Runtime + 'static> Runner<R> {
    pub fn host(&self) -> &Host<R> {
        &self.store.data().host
    }
    pub fn host_mut(&mut self) -> &mut Host<R> {
        &mut self.store.data_mut().host
    }
    pub fn run(&mut self, budget: u32) -> Result<u32, String>
    where
        R::Error: core::fmt::Debug,
    {
        if self.failed || self.store.data().error.is_some() {
            return Err("AOT runner stopped after an error".into());
        }
        let result = match self.run.call(&mut self.store, budget) {
            Ok(result) => result,
            Err(error) => {
                self.failed = true;
                return Err(format!("AOT execution: {error}"));
            }
        };
        if let Some(error) = &self.store.data().error {
            return Err(format!("AOT runtime: {error:?}"));
        }
        Ok(result)
    }
}

